"""The `coordination` schema: jobs, the outbox, and the delivery ledger.

Revision ID: 0034
Revises: 0033
Create Date: 2026-08-26 00:00:00.000000

`coordination.jobs` is a unit of work for a worker. `(kind, key)` is unique while a job is live
(queued, running, or failed and waiting to retry), which is the cross-process overlap guard. A
worker claims with `FOR UPDATE SKIP LOCKED` and holds a lease (`locked_at` + `lease_seconds`),
renewed by heartbeat, so a dead worker's job is claimable again once the lease expires.

`coordination.outbox` holds events written inside the producing transaction, delivered by a worker
in id order. `coordination.event_deliveries` records one row per (event, subscriber) handled, so
delivering twice is visible and a database-writing subscriber can commit its effect and its
record together.

Disposable dev-chain DDL like its siblings: downgrade drops the schema, re-running upgrade is the
way back.
"""

