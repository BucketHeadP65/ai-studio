"""wiki schema: the four compile-private incremental-ingestion state tables.

Revision ID: 0006
Revises: 0005
Create Date: 2026-06-28 00:00:05.000000

Adds the per-collection, compile-private state that turns ``engram compile`` from a
full O(corpus) rebuild into true incremental ingestion:

* ``wiki.compile_manifest`` — one row per compiled file mapping its ``path`` to its
  raw ``content_hash`` and resolution ``identity_hash`` (plus the ``page_id`` /
  ``zotero_key`` it produced). Re-hashing all files and diffing against it yields the
  ``{added, removed, content-changed}`` partition without parsing.
* ``wiki.link_refs`` — every outbound link target a page declares, resolved **and**
  dangling, keyed by the lower-cased ``raw_target`` so the inbound closure is a name
  query (``WHERE raw_target = :name``) — something ``wiki.edges`` (resolved-only,
  id-keyed, no raw target) cannot answer.
* ``wiki.lint_store`` — each page's persisted lint issues, so the whole-vault
  ``n_errors`` CI gate is reassembled as ``stored(clean pages) ∪ recomputed(dirty)``.
* ``wiki.compile_fingerprint`` — the single per-collection
  ``compiler_version + spec_hash + registry_hash + embed_model`` row; a mismatch is a
  global invalidator forcing a ``--full`` rebuild.

The DDL is hand-written through ``op.execute`` (the convention 0001 set for every
``wiki.*`` table; these revisions are not autogenerated). Postgres does not auto-index
foreign keys, so every FK gets an
explicit index alongside the closure-query indexes. ``link_refs.src_page_id`` is a FK
to ``wiki.pages`` with ``ON DELETE CASCADE`` (deleting a page auto-clears its outbound
refs); ``lint_store.page_id`` is deliberately **not** a FK — parse-error issues are
keyed by file path before any page row exists, and the incremental path manages the
lint lifecycle explicitly.

**No role grants — exactly as the sibling ``wiki.*`` tables (0001 / 0005).** These four
tables are compile-private: ``compile`` stays the only writer, ``wiki_reader`` (0003)
gets **no** grant on them, and they appear in **no** ``api`` view/function. So mirroring
the siblings means granting nothing here; adding a direct ``wiki_reader`` SELECT would
breach that tested invariant.

Downgrade drops the four tables, ``link_refs`` (the FK-bearing child of ``wiki.pages``)
included — a coarse teardown for a disposable dev DB, the same posture the sibling
migrations take (re-running ``upgrade`` is the intended path).
"""

from __future__ import annotations

from alembic import op

revision: str = "0006"
down_revision: str | None = "0005"
branch_labels: str | tuple[str, ...] | None = None
depends_on: str | tuple[str, ...] | None = None


def upgrade() -> None:
    """Create the four compile-private tables + their FK/closure indexes."""
    # wiki.compile_manifest — one row per compiled file (note or source mirror).
    op.execute(
        """
        CREATE TABLE wiki.compile_manifest (
          collection    text NOT NULL,
          path          text NOT NULL,
          kind          text NOT NULL,
          content_hash  text NOT NULL,
          identity_hash text NOT NULL,
          page_id       text,
          zotero_key    text,
          compiled_at   timestamptz NOT NULL DEFAULT now(),
          PRIMARY KEY (collection, path)
        )
        """
    )
    op.execute("CREATE INDEX ix_compile_manifest_page ON wiki.compile_manifest (collection, page_id)")
    op.execute("CREATE INDEX ix_compile_manifest_ztk  ON wiki.compile_manifest (collection, zotero_key)")

    # wiki.link_refs — every outbound link target (resolved + dangling), keyed for the name closure.
    # dst_id is nullable text with no FK so an unresolved (dangling) target stays representable
    # rather than being rejected — loose-coupling-by-design.
    op.execute(
        """
        CREATE TABLE wiki.link_refs (
          id               bigserial PRIMARY KEY,
          collection       text NOT NULL,
          src_page_id      text NOT NULL REFERENCES wiki.pages(id) ON DELETE CASCADE,
          src_kind         text NOT NULL,
          rel              text NOT NULL,
          raw_target       text NOT NULL,
          dst_id           text,
          provenance_claim text
        )
        """
    )
    op.execute("CREATE INDEX ix_link_refs_target ON wiki.link_refs (collection, raw_target)")
    op.execute("CREATE INDEX ix_link_refs_src    ON wiki.link_refs (collection, src_page_id)")
    op.execute("CREATE INDEX ix_link_refs_dst    ON wiki.link_refs (collection, dst_id)")

    # wiki.lint_store — persisted per-page lint issues for whole-vault report reassembly.
    # page_id is deliberately not a FK — parse-error issues predate any wiki.pages row, so a FK
    # would reject exactly the rows this store records; orphans are managed by the lifecycle.
    op.execute(
        """
        CREATE TABLE wiki.lint_store (
          id         bigserial PRIMARY KEY,
          collection text NOT NULL,
          page_id    text NOT NULL,
          severity   text NOT NULL,
          rule       text NOT NULL,
          message    text NOT NULL,
          anchor     text
        )
        """
    )
    op.execute("CREATE INDEX ix_lint_store_page     ON wiki.lint_store (collection, page_id)")
    op.execute("CREATE INDEX ix_lint_store_severity ON wiki.lint_store (collection, severity)")

    # wiki.compile_fingerprint — global-invalidator single row per collection.
    op.execute(
        """
        CREATE TABLE wiki.compile_fingerprint (
          collection       text PRIMARY KEY,
          compiler_version text NOT NULL,
          spec_hash        text NOT NULL,
          registry_hash    text NOT NULL,
          embed_model      text NOT NULL,
          compiled_at      timestamptz NOT NULL DEFAULT now()
        )
        """
    )


def downgrade() -> None:
    """Drop the four compile-state tables (the FK-bearing ``link_refs`` included)."""
    op.execute("DROP TABLE IF EXISTS wiki.compile_fingerprint")
    op.execute("DROP TABLE IF EXISTS wiki.lint_store")
    op.execute("DROP TABLE IF EXISTS wiki.link_refs")
    op.execute("DROP TABLE IF EXISTS wiki.compile_manifest")
