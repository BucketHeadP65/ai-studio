# noqa: INP001 — alembic env.py is a script, not a package (mirrors server's per-file ignore)
"""Alembic environment for the memory app.

Mirrors the server's ``alembic/env.py`` idiom: an **async** engine with a
``NullPool``. The migration CLI reads the **same** ``config/application_settings.json``
the app does and honours the **same** ``APP_*`` override vocabulary — there is one
configuration system across the app and migrations. It reads only a *subset* of the
keys (DB URL + retrieval policy), directly from the JSON, **without** constructing the
app's full settings model — whose required ``knowledge_base`` must not gate a migration (you
migrate a fresh DB before you have a knowledge base).

Resolution precedence for the admin URL, in order:

1. ``config.attributes["sqlalchemy_url"]`` — the programmatic seam the testcontainers
   harness uses to point ``alembic upgrade head`` at a throwaway database;
2. the ``APP_INFRASTRUCTURE__DATABASE__URL`` environment variable, the override seam
   (and the cloud-target seam), identical to the app's nested-env override;
3. ``infrastructure.database.url`` from ``config/application_settings.json``.

The BM25 dialect and link-graph backend resolve the same way: a programmatic
``config.attributes["dialect"]`` / ``config.attributes["graph_backend"]`` test seam first
(so a test pins the migration grammar without a process-wide ``APP_*`` env that would
pollute the settings unit tests), then the ``APP_RETRIEVAL__DIALECT`` /
``APP_RETRIEVAL__GRAPH_BACKEND`` env vars, then ``retrieval.dialect`` /
``retrieval.graph_backend`` from the JSON, then the portable defaults (``pg_textsearch`` /
``age``). The ``kb_reader`` login password is derived from the resolved ``reader_url``
(single source of truth), so the role's password always matches the URL the serving layer
connects with.

``target_metadata`` is taken from :data:`engram.db.contracts.KbBase.metadata`, which the side-effect
ORM imports below (``engram.indexing.infrastructure.orm`` + ``engram.evals.shared.infrastructure.orm``) populate with every
``kb.*`` table. These migrations are hand-written ``op.execute`` DDL, so the populated metadata
is there so any *future* autogenerated revision diffs against a faithful model.

``prepend_sys_path = . src`` in ``alembic.ini`` puts ``src/`` on ``sys.path``, so
``from engram.config import …`` / ``from engram.db.contracts import …`` / ``from engram.init.contracts import …``
resolve here.
"""

from __future__ import annotations

import asyncio
import json
import os

from logging.config import fileConfig
from pathlib import Path
from typing import TYPE_CHECKING

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import create_async_engine

import engram.evals.shared.infrastructure.orm as _evals_orm  # noqa: F401 — registers kb.evaluation_runs / kb.evaluation_case_results (side-effect import)
import engram.indexing.infrastructure.orm as _index_orm  # noqa: F401 — registers the kb.* ORM tables on KbBase.metadata (side-effect import)

from engram.config import DbDialect, GraphBackend
from engram.db.contracts import KbBase
from engram.init.contracts import resolve_db_url
from engram.retrieval.graph_backend import GraphBackendSql, build_graph_backends
from engram.retrieval.search_dialect import SearchDialect, build_search_dialects

if TYPE_CHECKING:
    from sqlalchemy.engine import Connection

# The application-settings JSON, resolved relative to this script (``engram/alembic/env.py``
# → ``engram/config/``). Read directly here — NOT via ``ApplicationSettings`` — so the
# migration CLI never triggers the required-``knowledge_base`` validation just to read the DB URL.
_CONFIG_DIR = Path(__file__).parent.parent / "config"
_CONFIG_JSON = _CONFIG_DIR / "application_settings.json"

config = context.config

# `disable_existing_loggers=False`: the default silences every logger created before this point,
# so a migration run inside the studio or harness process (or a test bed) would mute the app's own logs.
if config.config_file_name is not None:
    fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = KbBase.metadata


def _config_value(*keys: str) -> str | None:
    """Read a dotted key from ``config/application_settings.json``.

    Walks ``keys`` into the (gitignored) JSON config and returns the string value at that
    path, or ``None`` when the file or key is absent / non-string — the migration CLI's
    no-env path for the admin URL / reader URL / dialect / graph backend, read without
    constructing ``ApplicationSettings``.

    Args:
        *keys: The dotted path into the JSON (e.g. ``"infrastructure", "database", "url"``).

    Returns:
        The string value at that path, or ``None`` if absent / non-string.
    """
    if not _CONFIG_JSON.is_file():
        return None
    node: object = json.loads(_CONFIG_JSON.read_text(encoding="utf-8"))
    for key in keys:
        if not isinstance(node, dict) or key not in node:
            return None
        node = node[key]
    return node if isinstance(node, str) else None


def _resolve_search_dialect() -> SearchDialect:
    """Resolve the BM25 :class:`SearchDialect` the migrations should emit SQL for.

    Reads ``config.attributes["dialect"]`` (the programmatic test seam) first, then
    ``APP_RETRIEVAL__DIALECT`` (the app's nested-env override), then ``retrieval.dialect``
    from the JSON config, then defaults to :attr:`engram.config.DbDialect.PG_TEXTSEARCH`, and selects
    the matching concrete dialect from a fresh registry built by
    :func:`~engram.retrieval.search_dialect.build_search_dialects`. With none of those set, this
    returns the ``pg_textsearch`` dialect.

    The ``config.attributes["dialect"]`` seam lets the testcontainers harness pin a bed's
    migration grammar without a process-wide ``APP_RETRIEVAL__DIALECT`` (which would pollute the
    pydantic-settings unit tests that assert the default), mirroring how ``sqlalchemy_url`` is
    threaded through ``config.attributes``. In the test-harness path
    (``config.attributes["sqlalchemy_url"]`` set) the JSON config is skipped — a dev machine
    whose ``application_settings.json`` points at the cloud must not bleed into a testcontainer
    migration. Mirrors how :func:`_resolve_reader_password` special-cases the harness.
    """
    json_dialect = None if config.attributes.get("sqlalchemy_url") else _config_value("retrieval", "dialect")
    attr_dialect = config.attributes.get("dialect")
    dialect = DbDialect(attr_dialect or os.environ.get("APP_RETRIEVAL__DIALECT") or json_dialect or DbDialect.PG_TEXTSEARCH)
    return build_search_dialects().select(dialect)


def _resolve_graph_backend() -> GraphBackendSql:
    """Resolve the link-graph :class:`GraphBackendSql` the migrations should emit SQL for.

    Reads ``config.attributes["graph_backend"]`` (the programmatic test seam) first, then
    ``APP_RETRIEVAL__GRAPH_BACKEND`` (the app's nested-env override), then
    ``retrieval.graph_backend`` from the JSON config, then defaults to
    :attr:`engram.config.GraphBackend.AGE`, and selects the matching concrete backend from a fresh
    registry built by :func:`~engram.retrieval.graph_backend.build_graph_backends`. With none of
    those set, this returns the Apache AGE backend.

    The ``config.attributes["graph_backend"]`` seam lets the testcontainers harness pin a bed's
    graph backend without a process-wide ``APP_RETRIEVAL__GRAPH_BACKEND`` (which would pollute the
    pydantic-settings unit tests that assert the default). The seam is read here before the caller
    below overwrites the same slot with the resolved strategy 0004 consumes, so the test's value
    wins for this resolution. As with :func:`_resolve_search_dialect`, the JSON config is skipped
    in the test-harness path (``config.attributes["sqlalchemy_url"]`` set) so a dev's cloud-pointed
    ``application_settings.json`` cannot bleed into a testcontainer migration.
    """
    json_backend = None if config.attributes.get("sqlalchemy_url") else _config_value("retrieval", "graph_backend")
    attr_backend = config.attributes.get("graph_backend")
    backend = GraphBackend(attr_backend or os.environ.get("APP_RETRIEVAL__GRAPH_BACKEND") or json_backend or GraphBackend.AGE)
    return build_graph_backends().select(backend)


def _resolve_url() -> str:
    """Resolve the admin database URL by delegating to the one shared precedence ladder.

    Thin caller over :func:`engram.init.contracts.resolve_db_url`: this env passes the
    ``config.attributes["sqlalchemy_url"]`` programmatic test seam as the highest-priority
    ``override``, and the shared resolver applies the rest of the ladder
    (``APP_INFRASTRUCTURE__DATABASE__URL`` env var → ``infrastructure.database.url`` from the JSON
    config), raising if none yields a URL. The precedence rule lives in exactly one place,
    so the migration CLI and ``engram init`` can never drift.
    """
    override = config.attributes.get("sqlalchemy_url")
    return resolve_db_url(override if isinstance(override, str) else None)


def _resolve_reader_password() -> str | None:
    """The ``kb_reader`` login password, parsed from the resolved reader URL (single source of truth).

    In the test-harness path (``config.attributes["sqlalchemy_url"]`` set), returns ``None`` so the
    role migration uses its deterministic dev fallback — keeping the integration suite
    machine-independent. Otherwise reads ``APP_INFRASTRUCTURE__DATABASE__READER_URL`` / the JSON
    ``infrastructure.database.reader_url`` and extracts its password, so the role's password always
    matches the URL the serving layer connects with.
    """
    if config.attributes.get("sqlalchemy_url"):
        return None
    reader_url = os.environ.get("APP_INFRASTRUCTURE__DATABASE__READER_URL") or _config_value("infrastructure", "database", "reader_url")
    return make_url(reader_url).password if reader_url else None


def run_migrations_offline() -> None:
    """Emit migration SQL to stdout without connecting to a database."""
    context.configure(url=_resolve_url(), target_metadata=target_metadata, literal_binds=True, dialect_opts={"paramstyle": "named"})

    with context.begin_transaction():
        context.run_migrations()


def _do_run_migrations(connection: Connection) -> None:
    context.configure(connection=connection, target_metadata=target_metadata)
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    """Apply migrations through an async engine (works with ``asyncpg``)."""
    connectable = create_async_engine(_resolve_url(), poolclass=pool.NullPool)
    async with connectable.connect() as connection:
        await connection.run_sync(_do_run_migrations)
    await connectable.dispose()


def run_migrations_online() -> None:
    """Connect to the database and apply migrations."""
    asyncio.run(run_async_migrations())


# Stash the resolved BM25 dialect, link-graph backend, and reader password on the Config so the
# version modules read them from ``context.config.attributes[...]`` — the idiomatic alembic
# channel for handing application objects from env.py down to a revision's ``upgrade()`` without
# a module-level global. Set once here, before either migration path runs, in both modes.
config.attributes["search_dialect"] = _resolve_search_dialect()
config.attributes["graph_backend"] = _resolve_graph_backend()
config.attributes["reader_password"] = _resolve_reader_password()

if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
