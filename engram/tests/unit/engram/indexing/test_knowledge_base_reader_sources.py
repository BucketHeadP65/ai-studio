"""Reader discovery: multi-folder page types, explicit files, and generated-file skipping."""

from pathlib import Path

from engram.indexing.contracts import FilesystemKnowledgeBaseReader


def _write(root: Path, rel: str, text: str) -> None:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


class TestReaderSources:
    def test_note_files_are_yielded(self, tmp_path: Path) -> None:
        _write(tmp_path, "CONTEXT-MAP.md", "---\nid: context-map\n---\nbody")
        reader = FilesystemKnowledgeBaseReader(tmp_path / "docs", note_files=("../CONTEXT-MAP.md",))
        (tmp_path / "docs" / "Units").mkdir(parents=True)
        docs = list(reader.unit_documents())
        assert [d.path for d in docs] == ["../CONTEXT-MAP.md"]

    def test_note_files_path_has_no_backslashes(self, tmp_path: Path) -> None:
        # `_read` (glob surfaces) and `_read_note_file` (explicit note_files) must key the
        # in-batch dedupe the same way — forward-slash-only — or the same file reached by
        # two spellings could index twice.
        _write(tmp_path, "CONTEXT-MAP.md", "---\nid: context-map\n---\nbody")
        reader = FilesystemKnowledgeBaseReader(tmp_path / "docs", note_files=("../CONTEXT-MAP.md",))
        (tmp_path / "docs" / "Units").mkdir(parents=True)

        docs = list(reader.unit_documents())

        assert all("\\" not in d.path for d in docs)

    def test_generated_files_are_skipped(self, tmp_path: Path) -> None:
        _write(tmp_path, "docs/memory/real.md", "---\nid: mu.real\n---\nbody")
        _write(tmp_path, "docs/memory/index.md", "<!-- GENERATED by split_doc -->\nnot a note")
        reader = FilesystemKnowledgeBaseReader(tmp_path / "docs", note_folders=("memory",))
        assert [d.path for d in reader.unit_documents()] == ["memory/real.md"]
