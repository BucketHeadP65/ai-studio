-- ---------------------------------------------------------------------------
-- The chat record's tables: every pydantic-ai message once, every step as entries.
-- Applied with `core.ai.history.contracts.create_record_schema`. Idempotent: every statement creates only what is missing.
-- A conversation is an id here. The application owns the conversations table and the foreign
-- keys to it, so deleting a conversation and taking the record with it is the application's doing.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS runs (
    run_id          text PRIMARY KEY,
    conversation_id uuid NOT NULL,
    parent_run_id   text,
    agent_name      text,
    started_at      timestamptz NOT NULL,
    metadata        jsonb NOT NULL DEFAULT '{}',
    registration_id text
);
CREATE INDEX IF NOT EXISTS runs_by_conversation ON runs (conversation_id, started_at);

CREATE TABLE IF NOT EXISTS run_events (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    run_id          text NOT NULL REFERENCES runs (run_id) ON DELETE CASCADE,
    seq             integer NOT NULL,
    kind            text NOT NULL,
    step_index      integer NOT NULL,
    at              timestamptz NOT NULL,
    tool_call_id    text,
    tool_name       text,
    error           text,
    metadata        jsonb NOT NULL DEFAULT '{}',
    PRIMARY KEY (run_id, seq)
);
CREATE UNIQUE INDEX IF NOT EXISTS run_events_id_key ON run_events (id);

CREATE TABLE IF NOT EXISTS messages (
    conversation_id uuid NOT NULL,
    ordinal         integer NOT NULL,
    key             varchar(32) NOT NULL,
    kind            text NOT NULL,
    first_run_id    text NOT NULL,
    first_seq       integer NOT NULL,
    created_at      timestamptz NOT NULL,
    PRIMARY KEY (conversation_id, ordinal)
);
CREATE UNIQUE INDEX IF NOT EXISTS messages_by_key ON messages (conversation_id, key);

CREATE TABLE IF NOT EXISTS message_forms (
    conversation_id uuid NOT NULL,
    ordinal         integer NOT NULL,
    form            smallint NOT NULL,
    content         jsonb NOT NULL,
    content_digest  varchar(64) NOT NULL,
    text_content    text NOT NULL DEFAULT '',
    digest          varchar(64),
    length          integer,
    PRIMARY KEY (conversation_id, ordinal, form),
    FOREIGN KEY (conversation_id, ordinal) REFERENCES messages (conversation_id, ordinal) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS message_stamps (
    conversation_id uuid NOT NULL,
    ordinal         integer NOT NULL,
    version         smallint NOT NULL,
    stamps          jsonb NOT NULL,
    stamps_digest   varchar(64) NOT NULL,
    PRIMARY KEY (conversation_id, ordinal, version),
    FOREIGN KEY (conversation_id, ordinal) REFERENCES messages (conversation_id, ordinal) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS instructions (
    digest varchar(64) PRIMARY KEY,
    text   text NOT NULL
);

CREATE TABLE IF NOT EXISTS steps (
    run_id          text NOT NULL REFERENCES runs (run_id) ON DELETE CASCADE,
    seq             integer NOT NULL,
    step_index      integer NOT NULL,
    at              timestamptz NOT NULL,
    state           text NOT NULL,
    entries         integer[] NOT NULL,
    PRIMARY KEY (run_id, seq)
);

CREATE TABLE IF NOT EXISTS request_parameters (
    digest     varchar(64) PRIMARY KEY,
    parameters jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS step_parameters (
    run_id     text NOT NULL REFERENCES runs (run_id) ON DELETE CASCADE,
    step_index integer NOT NULL,
    digest     varchar(64) NOT NULL REFERENCES request_parameters (digest),
    PRIMARY KEY (run_id, step_index)
);

CREATE TABLE IF NOT EXISTS tool_effects (
    run_id          text NOT NULL REFERENCES runs (run_id) ON DELETE CASCADE,
    tool_call_id    text NOT NULL,
    tool_name       text NOT NULL,
    status          text NOT NULL,
    started_at      timestamptz NOT NULL,
    ended_at        timestamptz,
    idempotency_key text,
    effect_summary  text,
    PRIMARY KEY (run_id, tool_call_id)
);

CREATE TABLE IF NOT EXISTS continuation_attempts (
    conversation_id uuid NOT NULL,
    attempt_id varchar(64) NOT NULL,
    expected_revision bigint NOT NULL CHECK (expected_revision >= 0),
    status text NOT NULL CHECK (status IN ('started', 'completed')),
    run_id text NOT NULL,
    snapshot_seq integer,
    checkpoint_digest varchar(64),
    output jsonb,
    output_digest varchar(64),
    started_at timestamptz NOT NULL,
    completed_at timestamptz,
    PRIMARY KEY (conversation_id, attempt_id),
    CHECK (
        (status = 'started' AND snapshot_seq IS NULL AND checkpoint_digest IS NULL AND output IS NULL
         AND output_digest IS NULL AND completed_at IS NULL)
        OR
        (status = 'completed' AND snapshot_seq IS NOT NULL AND checkpoint_digest IS NOT NULL AND output IS NOT NULL
         AND output_digest IS NOT NULL AND completed_at IS NOT NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS continuation_one_started
    ON continuation_attempts (conversation_id) WHERE status = 'started';
CREATE TABLE IF NOT EXISTS continuation_heads (
    conversation_id uuid PRIMARY KEY,
    revision bigint NOT NULL CHECK (revision > 0),
    attempt_id varchar(64) NOT NULL,
    FOREIGN KEY (conversation_id, attempt_id)
        REFERENCES continuation_attempts (conversation_id, attempt_id)
);
